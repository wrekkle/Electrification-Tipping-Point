# -*- coding: utf-8 -*-
"""Demand generation: Poisson arrivals, Beta EV share, Binomial composition,
and a non-homogeneous Poisson process generated by thinning.

Hierarchy (as required by the v2 draft): R ~ Beta(mean r) once per scenario,
then D_EV | A, R ~ Binomial(A, R), D_ICE = A - D_EV.  The fluid approximation
D_EV = A * R is available only as an explicitly-flagged comparison switch.
"""
from __future__ import annotations

import math

import numpy as np


class DemandError(ValueError):
    pass


# --------------------------------------------------------------------------
# Beta parametrisation and legality domain
# --------------------------------------------------------------------------
def beta_parameters(mean, variance):
    """Return (alpha, beta) for a Beta with given mean/variance.

    Raises DemandError when the pair is outside the Beta support:
    it must hold 0 < mean < 1 and 0 < variance < mean * (1 - mean).
    """
    if not (0.0 < mean < 1.0):
        raise DemandError("Beta mean must be in (0,1); got %r" % mean)
    ceiling = mean * (1.0 - mean)
    if not (0.0 < variance < ceiling):
        raise DemandError(
            "Beta variance %r inadmissible for mean %r: need 0 < v < %.6f"
            % (variance, mean, ceiling))
    common = ceiling / variance - 1.0
    return common * mean, common * (1.0 - mean)


def clamp_variance(mean, variance, ceiling_frac=0.99):
    """Return (variance_used, clamped) inside the open Beta domain."""
    if not (0.0 < mean < 1.0):
        mean = min(max(mean, 1e-9), 1.0 - 1e-9)
    cap = ceiling_frac * mean * (1.0 - mean)
    if variance <= 0.0:
        return 1e-12, True
    if variance >= cap:
        return cap, True
    return float(variance), False


def beta_parameters_safe(mean, variance, ceiling_frac=0.99):
    v, clamped = clamp_variance(mean, variance, ceiling_frac)
    return beta_parameters(mean, v), v, clamped


# --------------------------------------------------------------------------
# Scenario draws
# --------------------------------------------------------------------------
def draw_scenarios(rng, n_scen, arrivals_mean, r, beta_variance=None,
                   composition="beta", beta_ceiling=0.99):
    """Draw (A, D_EV, D_ICE, R) for n_scen days at EV share r.

    composition:
      beta      -- R ~ Beta(mean r, variance beta_variance); D_EV | A,R ~ Bin(A,R)
      binomial  -- per-vehicle independent EV: D_EV | A ~ Bin(A, r)
      fluid     -- D_EV = A * r (non-integer comparison only)
    """
    if arrivals_mean < 0:
        raise DemandError("arrivals_mean must be non-negative")
    A = rng.poisson(arrivals_mean, size=n_scen).astype(np.int64)
    if composition == "fluid":
        R = np.full(n_scen, float(r))
        D_EV = A.astype(float) * R
        D_ICE = A.astype(float) - D_EV
        return {"A": A, "R": R, "D_EV": D_EV, "D_ICE": D_ICE,
                "clamped": np.zeros(n_scen, dtype=bool)}
    if composition == "binomial":
        R = np.full(n_scen, float(r))
        D_EV = rng.binomial(A, r).astype(np.int64)
        D_ICE = A - D_EV
        return {"A": A, "R": R, "D_EV": D_EV, "D_ICE": D_ICE,
                "clamped": np.zeros(n_scen, dtype=bool)}
    if composition == "beta":
        if beta_variance is None:
            raise DemandError("beta composition requires beta_variance")
        if r <= 1e-9 or r >= 1.0 - 1e-9:
            # boundary EV share: Beta degenerates, use the deterministic limit
            R = np.full(n_scen, float(r))
            D_EV = rng.binomial(A, np.clip(R, 0.0, 1.0)).astype(np.int64)
            D_ICE = A - D_EV
            return {"A": A, "R": R, "D_EV": D_EV, "D_ICE": D_ICE,
                    "alpha": float("nan"), "beta": float("nan"),
                    "variance_used": 0.0,
                    "clamped": np.ones(n_scen, dtype=bool)}
        (a, b), var_used, clamped = beta_parameters_safe(
            r, beta_variance, beta_ceiling)
        R = rng.beta(a, b, size=n_scen)
        D_EV = rng.binomial(A, np.clip(R, 0.0, 1.0)).astype(np.int64)
        D_ICE = A - D_EV
        return {"A": A, "R": R, "D_EV": D_EV, "D_ICE": D_ICE,
                "alpha": a, "beta": b, "variance_used": var_used,
                "clamped": np.full(n_scen, clamped, dtype=bool)}
    raise DemandError("unknown composition mode %r" % composition)


def check_integer_conservation(scen):
    if not np.allclose(scen["D_EV"] + scen["D_ICE"], scen["A"], atol=0.0):
        raise DemandError("integer conservation D_EV + D_ICE = A violated")


def poisson_moments_check(rng, mean, n=50000):
    draw = rng.poisson(mean, size=n).astype(float)
    return {"sample_mean": float(draw.mean()),
            "sample_variance": float(draw.var()),
            "relative_gap": abs(float(draw.mean() - draw.var())) / max(mean, 1e-9)}


# --------------------------------------------------------------------------
# NHPP via thinning (Lewis & Shedler)
# --------------------------------------------------------------------------
def thinning_times(rng, intensity, t_end, lam_star=None):
    """Generate event times of an NHPP with piecewise-constant intensity(t).

    intensity is a callable returning events/hour for a scalar or array t.
    Returns a sorted numpy array of event times in [0, t_end).
    """
    if lam_star is None:
        lam_star = float(np.max(np.atleast_1d(intensity(np.linspace(0, t_end, 512)))))
    if lam_star <= 0:
        return np.empty(0)
    accepted = []
    t = 0.0
    while t < t_end:
        t += float(rng.exponential(1.0 / lam_star))
        if t >= t_end:
            break
        lam = intensity(t)
        lam = float(np.asarray(lam).reshape(-1)[0])
        if rng.random() < lam / lam_star:
            accepted.append(t)
    return np.asarray(accepted, dtype=float)


def piecewise_intensity(rate_by_hour, t0=0.0):
    rates = np.asarray(rate_by_hour, dtype=float)
    if np.any(rates < 0):
        raise DemandError("intensities must be non-negative")

    def fn(t):
        arr = np.atleast_1d(np.asarray(t, dtype=float))
        idx = np.floor(arr - t0).astype(int)
        idx = np.clip(idx, 0, len(rates) - 1)
        out = rates[idx]
        return float(out[0]) if np.ndim(t) == 0 else out
    return fn


def simulate_day_arrivals(rng, config, r, composition, beta_variance,
                         beta_ceiling, q=None, arrival_scale=1.0):
    """One day of demand for the v2 event layer.

    Unit boundary (2026-10-29 revision): the non-homogeneous Poisson process is
    drawn in HOURS because the intensity table is events per hour, and the
    times are converted once, here, into MINUTES after opening.  Everything
    downstream (dwell, queueing, reposition, charging, release) is minutes.
    The returned record therefore exposes

        times_min   arrival times, minutes after opening (sorted)
        time_unit   "minute"
        arrival_scale  multiplier applied to the hourly intensity profile

    arrival_scale makes the two site labels real parameter differences (see
    evaluate.v2_lot_arrival_scale) instead of only different random seeds.
    """
    d = config["demand"]
    scale = float(arrival_scale)
    if not (scale > 0.0):
        raise DemandError("arrival_scale must be positive")
    rates = np.asarray(d["hourly_rate"], dtype=float) * scale
    t_end = float(d["window_hours"])
    lam = piecewise_intensity(rates)
    lam_star = float(np.max(rates))
    times_h = thinning_times(rng, lam, t_end, lam_star=lam_star)
    A = len(times_h)
    scen = draw_scenarios(rng, 1, A, r, beta_variance, composition, beta_ceiling)
    D_EV = int(scen["D_EV"][0])
    q = float(d["q"]) if q is None else float(q)
    n_charge = int(rng.binomial(D_EV, q)) if D_EV > 0 else 0
    classes = np.array(["icev"] * (A - D_EV) + ["ev_park"] * (D_EV - n_charge)
                       + ["ev_charge"] * n_charge, dtype=object)
    # shuffle the class labels over the (sorted) arrival times only
    classes = classes[rng.permutation(A)]
    return {
        "times_min": np.sort(times_h) * 60.0,
        "classes": classes,
        "q": q,
        "r_draw": float(scen["R"][0]),
        "arrival_scale": scale,
        "time_unit": "minute",
        "window_min": t_end * 60.0,
        "counts": {"A": A, "ev": D_EV, "ev_charge": n_charge,
                   "ev_park": D_EV - n_charge, "icev": A - D_EV},
    }


def dwell_times(rng, config, n):
    """Dwell time in minutes from a lognormal or an empirical table."""
    spec = config["demand"]["dwell"]
    if spec["kind"] == "lognormal":
        vals = rng.lognormal(mean=math.log(float(spec["mean_min"])),
                             sigma=float(spec["sigma_log"]), size=n)
    elif spec["kind"] == "empirical":
        table = spec["table"]
        vals = rng.choice(np.asarray(table["minutes"], dtype=float),
                          size=n, p=np.asarray(table["weights"], dtype=float))
    else:
        raise DemandError("unknown dwell kind %r" % spec["kind"])
    return np.clip(vals, float(spec["min_min"]), float(spec["max_min"]))


def energy_requests(rng, config, n):
    spec = config["demand"]["energy_kwh"]
    vals = rng.lognormal(mean=math.log(float(spec["mean_kwh"])),
                         sigma=float(spec["sigma_log"]), size=n)
    return np.clip(vals, float(spec["min_kwh"]), float(spec["max_kwh"]))
