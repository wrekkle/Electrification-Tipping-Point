# -*- coding: utf-8 -*-
"""Build the round-8 repro package index from files actually present.

Reads only; writes README.md, environment.json, commands.txt, inputs.sha256,
results_inventory.md inside research/round8_20261031/repro/.
Pending families are marked PENDING, never filled.
"""
import hashlib, json, os, platform, sys, csv

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
ROUND = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(ROUND))


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def rows(p):
    with open(p, encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


inputs = []
for rel in ("data/processed/public_parking_events.json",
            "data/processed/_window_events.csv",
            "data/raw/melbourne_parking_bay_arrivals_departures_2014_mq3i-cbxd.zip",
            "data/qa/source_stats.json"):
    p = os.path.join(ROUND, rel)
    if os.path.exists(p):
        inputs.append((rel, sha256(p), os.path.getsize(p)))
with open(os.path.join(HERE, "inputs.sha256"), "w", encoding="utf-8") as fh:
    for rel, h, size in inputs:
        fh.write("%s  %s  (%d bytes)\n" % (h, rel, size))

# manifests -> commands
runs = []
for sub in ("experiments", "experiments_main22", "experiments_condshare"):
    base = os.path.join(ROUND, sub)
    for fam in ("E1", "E2", "E3", "E4", "E5", "E6", "E7", "M", ""):
        mp = os.path.join(base, fam, "manifest.json") if fam else os.path.join(base, "manifest.json")
        if os.path.exists(mp):
            with open(mp, encoding="utf-8") as fh:
                m = json.load(fh)
            runs.append((sub + ("/" + fam if fam else ""), m.get("command"),
                         m.get("seed"), m.get("output_version"), mp))
with open(os.path.join(HERE, "commands.txt"), "w", encoding="utf-8") as fh:
    fh.write("# exact run commands copied from each family manifest.json\n")
    for name, cmd, seed, ver, mp in runs:
        fh.write("\n[%s]\ncommand: %s\nseed: %s | output_version: %s\nmanifest: %s\n"
                 % (name, cmd, seed, ver, os.path.relpath(mp, ROOT)))

# inventory of result files
lines = ["# Machine-output inventory", "",
         "Rows are data rows (CSV) or top-level entries as noted. Generated by collect_repro.py;",
         "nothing here is typed by hand.", "",
         "| family | file | rows | key columns |", "|---|---|---|---|"]
for sub in ("experiments_main22", "experiments", "experiments_condshare"):
    base = os.path.join(ROUND, sub)
    if not os.path.isdir(base):
        continue
    for dp, dn, fn in os.walk(base):
        for f in sorted(fn):
            if not f.endswith(".csv"):
                continue
            p = os.path.join(dp, f)
            try:
                rr = rows(p)
            except Exception:
                continue
            cols = list(rr[0].keys())[:6] if rr else []
            lines.append("| %s | %s | %d | %s |" % (
                os.path.relpath(dp, base).replace("\\", "/") or ".", f, len(rr),
                ", ".join(cols)))
with open(os.path.join(HERE, "results_inventory.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")

env = {
    "python": sys.version.split()[0],
    "platform": platform.platform(),
    "processor": platform.processor(),
    "engine_version": "r8-engine-v1-2026-10-31",
    "seed": 20261031,
    "bootstrap": {"n_boot": 1000, "method": "percentile", "unit": "site-day"},
    "packages": {},
}
for mod in ("numpy", "matplotlib", "docx"):
    try:
        m = __import__(mod)
        env["packages"][mod] = getattr(m, "__version__", "unknown")
    except Exception:
        pass
with open(os.path.join(HERE, "environment.json"), "w", encoding="utf-8") as fh:
    json.dump(env, fh, ensure_ascii=False, indent=1)

print(json.dumps({"inputs": inputs, "runs": len(runs), "env": env,
                  "inventory": os.path.join(HERE, "results_inventory.md")},
                 ensure_ascii=False, indent=1)[:3000])
